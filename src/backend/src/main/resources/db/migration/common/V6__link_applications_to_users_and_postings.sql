-- Replaces the Sprint 1 application prototype (V4), whose rows weren't linked to a
-- job seeker or a job posting, with real applications. Resumes now live in the
-- resume table (V5), so the old document column is no longer needed.
DROP TABLE application;

CREATE TABLE application (
    id         BIGINT                   GENERATED BY DEFAULT AS IDENTITY,
    person_id  INTEGER                  NOT NULL,
    post_id    INTEGER                  NOT NULL,
    status     VARCHAR(20)              NOT NULL,
    applied_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT application_pkey PRIMARY KEY (id),
    -- A job seeker can apply to each posting only once
    CONSTRAINT application_person_post_key UNIQUE (person_id, post_id),
    CONSTRAINT application_status_check
        CHECK (status IN ('APPLIED', 'UNDER_REVIEW', 'INTERVIEW', 'OFFERED', 'REJECTED')),
    CONSTRAINT application_person_id_fkey FOREIGN KEY (person_id) REFERENCES person_user (person_id) ON DELETE CASCADE,
    CONSTRAINT application_post_id_fkey FOREIGN KEY (post_id) REFERENCES job_postings (post_id) ON DELETE CASCADE
);

-- Let the database assign ids to new job postings, starting after any existing rows.
-- On Supabase post_id was already made an identity column by hand, so this only
-- runs where it isn't one yet. (H2 needs different syntax for this, see db/migration/h2.)
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_name = 'job_postings' AND column_name = 'post_id' AND is_identity = 'YES') THEN
        ALTER TABLE job_postings ALTER COLUMN post_id ADD GENERATED BY DEFAULT AS IDENTITY;
        PERFORM setval(pg_get_serial_sequence('job_postings', 'post_id'),
                       COALESCE((SELECT MAX(post_id) FROM job_postings), 0) + 1, false);
    END IF;
END $$;

package com.example.demo.controller;

import com.example.demo.model.Application;
import com.example.demo.model.ApplicationStatus;
import com.example.demo.repository.ApplicationRepository;
import com.example.demo.repository.EmployerUserRepository;
import com.example.demo.repository.PersonUserRepository;
import com.jayway.jsonpath.JsonPath;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.http.MediaType;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.mock.web.MockHttpSession;
import org.springframework.mock.web.MockMultipartFile;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.ResultActions;

import java.sql.Date;
import java.time.LocalDate;
import java.util.UUID;
import java.util.concurrent.atomic.AtomicInteger;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.multipart;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@SpringBootTest
@AutoConfigureMockMvc
class ApplicationControllerTests {

    // job_postings.post_id isn't generated by the database, so the tests pick the ids
    private static final AtomicInteger NEXT_POST_ID = new AtomicInteger(1000);

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private PersonUserRepository personUsers;

    @Autowired
    private EmployerUserRepository employerUsers;

    @Autowired
    private ApplicationRepository applications;

    // Job postings are created by the recruiter posting feature, so the tests insert them directly
    @Autowired
    private JdbcTemplate jdbc;

    // Registers a new account, logs in and returns the logged-in session
    private MockHttpSession loggedIn(String role, String email) throws Exception {
        String companyName = "Recruiter".equals(role) ? ",\"companyName\":\"Acme Corp\"" : "";
        mockMvc.perform(post("/api/auth/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"role\":\"" + role + "\",\"name\":\"Jane\",\"surname\":\"Doe\","
                                + "\"email\":\"" + email + "\",\"password\":\"secret123\","
                                + "\"phone\":\"514-555-1234\",\"address\":\"1455 De Maisonneuve Blvd W\","
                                + "\"city\":\"Montreal\",\"provinceState\":\"Quebec\",\"country\":\"Canada\","
                                + "\"postalCodeZip\":\"H3G 1M8\"" + companyName + "}"))
                .andExpect(status().isOk());

        return (MockHttpSession) mockMvc.perform(post("/api/auth/login")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"" + email + "\",\"password\":\"secret123\"}"))
                .andExpect(status().isOk())
                .andReturn()
                .getRequest()
                .getSession();
    }

    private static String uniqueEmail() {
        return "user-" + UUID.randomUUID() + "@example.com";
    }

    // A logged-in job seeker who has uploaded a resume, ready to apply
    private MockHttpSession jobSeekerWithResume(String email) throws Exception {
        MockHttpSession session = loggedIn("Job Seeker", email);
        mockMvc.perform(multipart("/api/resume")
                        .file(new MockMultipartFile("resume", "cv.pdf", "application/pdf",
                                ResumeControllerTests.contents("cv.pdf", "resume")))
                        .session(session))
                .andExpect(status().isCreated());
        return session;
    }

    private MockHttpSession jobSeekerWithResume() throws Exception {
        return jobSeekerWithResume(uniqueEmail());
    }

    // Inserts a job posting owned by a new recruiter and returns its id
    private Integer posting(LocalDate deadline) throws Exception {
        return posting(deadline, "Open");
    }

    private Integer posting(LocalDate deadline, String status) throws Exception {
        String recruiterEmail = uniqueEmail();
        loggedIn("Recruiter", recruiterEmail);
        Integer employerId = employerUsers.findByEmailIgnoreCase(recruiterEmail).orElseThrow().getId();

        int postId = NEXT_POST_ID.getAndIncrement();
        jdbc.update("INSERT INTO job_postings (employer_id, post_id, title, description, department, "
                        + "application_deadline, salary, required_skills, status) "
                        + "VALUES (?, ?, 'Junior Developer', 'Write and test Java code', 'Engineering', ?, '60000', 'Java', ?)",
                employerId, postId, Date.valueOf(deadline), status);
        return postId;
    }

    private Integer openPosting() throws Exception {
        return posting(LocalDate.now().plusDays(30));
    }

    private ResultActions apply(MockHttpSession session, Object postId) throws Exception {
        return mockMvc.perform(post("/api/applications")
                .contentType(MediaType.APPLICATION_JSON)
                .content("{\"postId\":" + postId + "}")
                .session(session));
    }

    // Applies and returns the new application's id
    private Long appliedId(MockHttpSession session, Integer postId) throws Exception {
        String body = apply(session, postId)
                .andExpect(status().isCreated())
                .andReturn().getResponse().getContentAsString();
        Number id = JsonPath.read(body, "$.application.id");
        return id.longValue();
    }

    // ---- Submitting -------------------------------------------------------

    @Test
    void jobSeekerCanApplyAndGetsConfirmation() throws Exception {
        String email = uniqueEmail();
        MockHttpSession session = jobSeekerWithResume(email);
        Integer postId = openPosting();

        apply(session, postId)
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.message").value("Application submitted successfully."))
                .andExpect(jsonPath("$.application.postId").value(postId))
                .andExpect(jsonPath("$.application.jobTitle").value("Junior Developer"))
                .andExpect(jsonPath("$.application.companyName").value("Acme Corp"))
                .andExpect(jsonPath("$.application.status").value("Applied"))
                .andExpect(jsonPath("$.application.appliedAt").isNotEmpty());

        // Stored and linked to the right job seeker and posting
        Integer personId = personUsers.findByEmailIgnoreCase(email).orElseThrow().getId();
        assertThat(applications.existsByPersonIdAndPostId(personId, postId)).isTrue();
    }

    @Test
    void cannotApplyTwiceToTheSameJob() throws Exception {
        MockHttpSession session = jobSeekerWithResume();
        Integer postId = openPosting();

        apply(session, postId).andExpect(status().isCreated());
        apply(session, postId)
                .andExpect(status().isConflict())
                .andExpect(jsonPath("$.message").value("You have already applied to this job."));
    }

    @Test
    void differentJobSeekersCanApplyToTheSameJob() throws Exception {
        Integer postId = openPosting();

        apply(jobSeekerWithResume(), postId).andExpect(status().isCreated());
        apply(jobSeekerWithResume(), postId).andExpect(status().isCreated());
    }

    @Test
    void applyRequiresLogin() throws Exception {
        apply(new MockHttpSession(), openPosting())
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.message").value("Please sign in first."));
    }

    @Test
    void recruitersCannotApply() throws Exception {
        MockHttpSession recruiter = loggedIn("Recruiter", uniqueEmail());

        apply(recruiter, openPosting())
                .andExpect(status().isForbidden())
                .andExpect(jsonPath("$.message").value("Only job seekers can apply for jobs."));
    }

    @Test
    void applyRequiresPostId() throws Exception {
        mockMvc.perform(post("/api/applications")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{}")
                        .session(jobSeekerWithResume()))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.message").value("Job posting id is required."));
    }

    @Test
    void applyRejectsUnknownPosting() throws Exception {
        apply(jobSeekerWithResume(), 999999)
                .andExpect(status().isNotFound())
                .andExpect(jsonPath("$.message").value("Job posting not found."));
    }

    @Test
    void canStillApplyOnTheDeadlineDay() throws Exception {
        Integer closesToday = posting(LocalDate.now());

        apply(jobSeekerWithResume(), closesToday)
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.application.status").value("Applied"));
    }

    @Test
    void applyRejectsClosedPosting() throws Exception {
        Integer closed = posting(LocalDate.now().plusDays(30), "Closed");

        apply(jobSeekerWithResume(), closed)
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.message").value("This job posting is no longer accepting applications."));
    }

    @Test
    void postingsWithoutAStatusCountAsOpen() throws Exception {
        apply(jobSeekerWithResume(), posting(LocalDate.now().plusDays(30), null))
                .andExpect(status().isCreated());
    }

    @Test
    void applyRejectsPostingPastItsDeadline() throws Exception {
        Integer expired = posting(LocalDate.now().minusDays(1));

        apply(jobSeekerWithResume(), expired)
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.message").value("This job posting is no longer accepting applications."));
    }

    @Test
    void applyRequiresAnUploadedResume() throws Exception {
        MockHttpSession noResume = loggedIn("Job Seeker", uniqueEmail());

        apply(noResume, openPosting())
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.message").value("Please upload your resume before applying."));
    }

    // ---- Tracking ---------------------------------------------------------

    @Test
    void jobSeekerSeesAllTheirApplications() throws Exception {
        MockHttpSession session = jobSeekerWithResume();

        apply(session, openPosting()).andExpect(status().isCreated());
        apply(session, openPosting()).andExpect(status().isCreated());

        mockMvc.perform(get("/api/applications").session(session))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.length()").value(2))
                .andExpect(jsonPath("$[0].status").value("Applied"))
                .andExpect(jsonPath("$[1].status").value("Applied"));
    }

    @Test
    void newJobSeekerHasNoApplications() throws Exception {
        mockMvc.perform(get("/api/applications").session(loggedIn("Job Seeker", uniqueEmail())))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.length()").value(0));
    }

    @Test
    void jobSeekersOnlySeeTheirOwnApplications() throws Exception {
        MockHttpSession owner = jobSeekerWithResume();
        MockHttpSession other = jobSeekerWithResume();
        Long applicationId = appliedId(owner, openPosting());

        mockMvc.perform(get("/api/applications/" + applicationId).session(owner))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("Applied"));

        mockMvc.perform(get("/api/applications/" + applicationId).session(other))
                .andExpect(status().isNotFound())
                .andExpect(jsonPath("$.message").value("Application not found."));

        mockMvc.perform(get("/api/applications").session(other))
                .andExpect(jsonPath("$.length()").value(0));
    }

    @Test
    void viewingApplicationsRequiresLogin() throws Exception {
        mockMvc.perform(get("/api/applications").session(new MockHttpSession()))
                .andExpect(status().isUnauthorized());
    }

    @Test
    void recruitersHaveNoApplicationsToView() throws Exception {
        mockMvc.perform(get("/api/applications").session(loggedIn("Recruiter", uniqueEmail())))
                .andExpect(status().isForbidden());
    }

    @Test
    void jobSeekerSeesTheCurrentStatus() throws Exception {
        MockHttpSession session = jobSeekerWithResume();
        Long applicationId = appliedId(session, openPosting());

        // Status changes come from the recruiter feature; here the change is made directly
        for (ApplicationStatus newStatus : ApplicationStatus.values()) {
            Application application = applications.findById(applicationId).orElseThrow();
            application.updateStatus(newStatus);
            applications.save(application);

            mockMvc.perform(get("/api/applications/" + applicationId).session(session))
                    .andExpect(status().isOk())
                    .andExpect(jsonPath("$.status").value(newStatus.getLabel()));
        }
    }
}
